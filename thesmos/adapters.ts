// ── Types ─────────────────────────────────────────────────────────────────────

export type AdapterTarget =
  | 'gemini'
  | 'claude'
  | 'cursor'
  | 'copilot'
  | 'codex'
  | 'agents';

export interface Rule {
  id: string;
  category: string;
  description: string;
  severity: Severity;
  tags: string[];
  example?: string;
}

export interface AdapterManifest {
  target: AdapterTarget;
  outputPath: string;
  generated: boolean;
  /** 'generated' on success; 'failed' when the write itself errored (see error). */
  status: 'generated' | 'failed';
  error?: string;
}

// ── Output paths ──────────────────────────────────────────────────────────────

export const ADAPTER_OUTPUT_PATHS: Record<AdapterTarget, string> = {
  gemini: 'GEMINI.md',
  claude: 'CLAUDE.md',
  cursor: '.cursor/rules/thesmos.mdc',
  copilot: '.github/copilot-instructions.md',
  codex: '.codex/thesmos.md',
  agents: 'AGENTS.md',
};

// ── Filter helpers (pure) ─────────────────────────────────────────────────────

export function getRulesByTag(rules: Rule[], tag: string): Rule[] {
  return rules.filter((r) => r.tags.includes(tag));
}

export function getRulesBySeverity(rules: Rule[], severity: Severity): Rule[] {
  return rules.filter((r) => r.severity === severity);
}

export function getRulesByCategory(rules: Rule[], categories: string[]): Rule[] {
  const set = new Set(categories);
  return rules.filter((r) => set.has(r.category));
}

// ── Per-target generators (pure) ──────────────────────────────────────────────

/**
 * Short per-target framing sentence — the one thing that actually differs
 * between targets (how each tool is expected to use governance). Everything
 * else in the thin body below is identical across all six targets.
 */
const TARGET_FRAMING: Record<AdapterTarget, string> = {
  gemini: 'The following governs code review in this repo.',
  claude: 'The following governs every task in this repo.',
  cursor: 'The following governs all code suggestions in this repo.',
  copilot: 'The following governs completions and reviews in this repo.',
  codex: 'The following governs all generated code in this repo.',
  agents: 'The following governs any agent or tool working in this repo.',
};

/**
 * Thin adapter body — replaces the old per-rule table entirely (Operation
 * Signal Phase 5). The full 1,137-rule catalog, with descriptions and code
 * examples, embedded in EVERY generated file, was the direct cause of
 * 130-165KB always-loaded adapters. The rule engine is deterministic and
 * queryable on demand (`thesmos explain`) — it does not need to be
 * memorized by an LLM on every single turn.
 *
 * Contains only: what Thesmos is responsible for, a short universal
 * constraint list (not a rule table), how governance decisions are made,
 * how to scan/doctor, how to inspect a specific rule, how to discover an
 * agent, and how to explain a denial. Target: comfortably under 8KB total
 * (this body + the target's own short preamble).
 */
function generateThinAdapterBody(config: ThesmosConfig, target: AdapterTarget): string {
  const parts = [
    `_Generated by Thesmos ${config.version} for **${config.project}**. Full rule catalog: \`.thesmos/RULES.md\`._`,
    '',
    TARGET_FRAMING[target],
    '',
    '## What Thesmos is responsible for',
    `Thesmos is a deterministic governance engine — a fixed rule set covering security, auth, database, API, and framework-specific issues, checked the same way on every run. It is a lookup engine, not a document to read end-to-end.`,
    '',
    '## Non-negotiable constraints',
    '- A BLOCKER finding must never ship. Fix it, or get explicit human sign-off before continuing.',
    '- Never bypass, suppress, or silently work around a BLOCKER-severity rule.',
    '- HIGH findings should be resolved before a task is considered done.',
    '- Prefer small, reversible, verified changes over large unreviewed ones.',
    '- Never overwrite content outside the `THESMOS:GENERATED` markers in this file.',
    '',
    '## How governance decisions are made',
    'Every finding carries a rule id, a severity (BLOCKER/HIGH/MEDIUM/LOW/TECH_DEBT), a message, and a suggested fix — deterministic, not a judgment call. `thesmos validate` gates on BLOCKER only.',
    '',
    '## Commands',
    '- `thesmos scan` — analyze the repo, write `.thesmos/report.json`',
    '- `thesmos review [--base=<ref>]` — show findings for changed files',
    '- `thesmos validate [--base=<ref>]` — gate: exits non-zero on any BLOCKER',
    '- `thesmos doctor` — verify the Thesmos installation itself is healthy',
    '',
    '## Inspecting a specific rule',
    '- `thesmos explain <RULE_ID>` — full detail + live violations for one rule',
    '- `thesmos explain search <query>` — find rules by keyword',
    '- `thesmos explain --list` — every rule id/category/severity',
    '- Full catalog with descriptions and examples: `.thesmos/RULES.md`',
    '',
    '## Discovering an agent',
    '- `thesmos agents:list` — specialist agents available in this repo',
    '- `thesmos pantheon:list` — the full Pantheon god-agent roster, if installed',
    '',
    '## Explaining a denial',
    'A blocked action states which rule fired, why, and a suggested fix inline. For more detail on a specific denial, run `thesmos explain <RULE_ID>` or inspect `.thesmos/report.json`.',
  ];
  return parts.join('\n');
}

