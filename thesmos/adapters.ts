// ── Adapter metadata ──────────────────────────────────────────────────────────

/** Metadata embedded inside every generated adapter section. No timestamps. */
export interface AdapterMeta {
  version: string;
  target: AdapterTarget;
  ruleCount: number;
}

/** Minimal catalog context passed to adapter builders — avoids importing catalog.ts. */
export interface AdapterCatalogEntry {
  id: string;
  name: string;
}

export interface AdapterCatalog {
  agents: AdapterCatalogEntry[];
  skills: AdapterCatalogEntry[];
  profile?: string;
}

/**
 * Compact pointer, not a roster. Enumerating every active agent/skill by
 * name inline (the previous behavior) scaled with the size of the catalog
 * itself — on a repo with the full Pantheon installed, this alone was
 * tens of KB, the second-largest driver of oversized adapters after the
 * per-rule table (Operation Signal Phase 5). "How to discover an agent" is
 * a command to run, not a list to memorize.
 */
function formatCatalogContext(catalog: AdapterCatalog): string {
  if (catalog.agents.length === 0 && catalog.skills.length === 0 && !catalog.profile) return '';
  const lines: string[] = ['', '---', '', '## Active Thesmos Context', ''];
  if (catalog.profile) lines.push(`**Profile:** \`${catalog.profile}\``);
  if (catalog.agents.length > 0) lines.push(`**Active agents:** ${catalog.agents.length}`);
  if (catalog.skills.length > 0) lines.push(`**Active skills:** ${catalog.skills.length}`);
  lines.push('', '_Run `thesmos catalog:list` to see them by name, or `thesmos agents:list` to discover invocation details._');
  return lines.join('\n');
}

/**
 * Parse the THESMOS:META comment from an adapter file.
 * Returns null when the comment is absent or malformed.
 */
export function parseAdapterMeta(content: string): AdapterMeta | null {
  const match = content.match(/<!--\s*THESMOS:META\s+(\{[^}]+\})\s*-->/);
  if (!match || !match[1]) return null;
  try {
    return JSON.parse(match[1]) as AdapterMeta;
  } catch {
    return null;
  }
}

/**
 * Returns whether an adapter file's embedded metadata is current.
 * Freshness is checked by ruleCount and version only — no timestamps.
 */
export function isAdapterFresh(
  content: string,
  rules: Rule[],
  config: ThesmosConfig
): { fresh: boolean; reason: string } {
  const meta = parseAdapterMeta(content);
  if (!meta) {
    return { fresh: false, reason: 'no metadata — run thesmos adapters to refresh' };
  }
  if (meta.ruleCount !== rules.length) {
    return {
      fresh: false,
      reason: `rule count mismatch: file has ${meta.ruleCount}, registry has ${rules.length}`,
    };
  }
  if (meta.version !== config.version) {
    return {
      fresh: false,
      reason: `version mismatch: file has ${meta.version}, current is ${config.version}`,
    };
  }
  return { fresh: true, reason: 'up to date' };
}

// ── Public pure merger ────────────────────────────────────────────────────────

/**
 * Merges a freshly generated rules section into an existing adapter document.
 * If the document is empty, uses the target-specific preamble as the base.
 * Idempotent: calling twice with identical input produces identical output.
 *
 * The generated section always begins with a THESMOS:META comment so that
 * isAdapterFresh() can verify the file without re-running the generator.
 */
export function buildAdapterContent(
  target: AdapterTarget,
  existing: string,
  rules: Rule[],
  config: ThesmosConfig,
  catalog?: AdapterCatalog
): string {
  const base =
    existing.trim() === '' ? ADAPTER_PREAMBLES[target](config) : existing;
  const meta: AdapterMeta = { version: config.version, target, ruleCount: rules.length };
  const metaComment = `<!-- THESMOS:META ${JSON.stringify(meta)} -->`;
  const catalogCtx = catalog ? formatCatalogContext(catalog) : '';
  const generated = `${metaComment}\n${RULE_GENERATORS[target](rules, config)}${catalogCtx}`;
  return injectGeneratedSection(base, 'rules', generated);
}

// ── Target detection ──────────────────────────────────────────────────────────

/**
 * Detects which AI-tool integrations already have a footprint in `root`.
 * `claude` and `agents` are always included — Claude Code is the primary
 * surface and AGENTS.md is the cross-tool convention — every other target
 * is included only when its integration directory/file already exists, so
 * `thesmos adapters`/`thesmos init` don't scatter files for tools the repo
 * doesn't use. Shared by both commands so detection can't drift between them.
 */
export function detectAdapterTargets(root: string): AdapterTarget[] {
  const detected: AdapterTarget[] = ['claude', 'agents'];
  if (existsSync(join(root, 'GEMINI.md'))) detected.push('gemini');
  if (existsSync(join(root, '.cursor')) || existsSync(join(root, '.cursorrules'))) detected.push('cursor');
  if (existsSync(join(root, '.github', 'copilot-instructions.md'))) detected.push('copilot');
  if (existsSync(join(root, '.codex'))) detected.push('codex');
  return detected;
}

// ── I/O orchestrator ──────────────────────────────────────────────────────────

/** Write `content` to `absPath` via a temp-file-then-rename swap — never leaves a partially-written file in place. */
function atomicWriteFileSync(absPath: string, content: string): void {
  const dir = dirname(absPath);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  const tmpPath = join(dir, `.${basename(absPath)}.tmp-${process.pid}-${Math.random().toString(36).slice(2)}`);
  writeFileSync(tmpPath, content, 'utf8');
  try {
    renameSync(tmpPath, absPath);
  } catch (err) {
    try { unlinkSync(tmpPath); } catch { /* best-effort cleanup of the temp file */ }
    throw err;
  }
}

/**
 * Writes adapter files for the requested targets under `root`.
 * Existing files are updated in-place (generated section only);
 * manually written content outside the markers is preserved.
 * Writes are atomic (temp file + rename) — a failure on one target never
 * leaves that file partially written, and never blocks the other targets.
 */
export function writeAllAdapters(
  root: string,
  rules: Rule[],
  config: ThesmosConfig,
  targets: AdapterTarget[] = [
    'gemini',
    'claude',
    'cursor',
    'copilot',
    'codex',
    'agents',
  ],
  catalog?: AdapterCatalog
): AdapterManifest[] {
  // Auto-generate context snapshot alongside adapters so CLAUDE.md step 1 always has fresh data.
  // Advisory only — a failure here must never block adapter generation — but it is reported
  // rather than swallowed, since a silently-broken snapshot is its own kind of drift.
  try {
    const capsule = generateContextCapsule(root);
    saveContextCapsule(root, capsule);
  } catch (err) {
    process.stderr.write(
      `thesmos adapters: context snapshot generation failed (non-fatal): ${err instanceof Error ? err.message : String(err)}\n`
    );
  }

  return targets.map((target) => {
    const relPath = ADAPTER_OUTPUT_PATHS[target];
    const absPath = join(root, relPath);
    try {
      const existing = existsSync(absPath) ? readFileSync(absPath, 'utf8') : '';
      const content = buildAdapterContent(target, existing, rules, config, catalog);
      atomicWriteFileSync(absPath, content);
      return { target, outputPath: relPath, generated: true, status: 'generated' };
    } catch (err) {
      return {
        target,
        outputPath: relPath,
        generated: false,
        status: 'failed',
        error: err instanceof Error ? err.message : String(err),
      };
    }
  });
}
